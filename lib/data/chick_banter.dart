/// Returns the character's small-talk and trivia lines, rotated by time.
List<String> chickBanterLines(Locale locale, DateTime now) {
  final pool = locale.languageCode == 'ja' ? _chickBanterJa : _chickBanterEn;
  if (pool.isEmpty) return const [];
  final start =
      (now.year * 367 + now.day * 53 + now.hour * 17 + now.minute) %
      pool.length;
  return [...pool.sublist(start), ...pool.sublist(0, start)];
}
